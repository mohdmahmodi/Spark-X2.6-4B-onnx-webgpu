"""Build the SVG icon sprite web/assets/icons.svg from pinned icon sets.

UI icons come from Lucide (ISC license), brand marks from Simple Icons (CC0). Pages reference them as
<svg><use href="assets/icons.svg#name"/></svg>; Lucide icons are stroked, brand marks filled.

usage: python tools/build_icons.py
"""
import re
import urllib.request
from pathlib import Path

LUCIDE = "https://cdn.jsdelivr.net/npm/lucide-static@1.55.0/icons/{}.svg"
SIMPLE = "https://cdn.jsdelivr.net/npm/simple-icons@16.34.0/icons/{}.svg"
LUCIDE_ICONS = ["arrow-right", "arrow-up", "brain", "check", "chevron-down", "chevron-right", "copy", "gauge", "menu",
                "sliders-horizontal", "square", "square-pen", "trash-2"]
BRANDS = {"github": "github", "x": "brand-x", "huggingface": "huggingface"}  # simple-icons slug -> sprite id
OUT = Path("web/assets/icons.svg")


def fetch(url):
    with urllib.request.urlopen(url) as r:
        return r.read().decode("utf-8")


def inner(svg):
    body = svg[svg.index(">", svg.index("<svg")) + 1: svg.rindex("</svg>")]
    body = re.sub(r"<title>.*?</title>", "", body)
    return " ".join(body.split())


def main():
    symbols = []
    for name in LUCIDE_ICONS:
        symbols.append(f'  <symbol id="{name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
                       f'stroke-linecap="round" stroke-linejoin="round">{inner(fetch(LUCIDE.format(name)))}</symbol>')
    for slug, sid in BRANDS.items():
        symbols.append(f'  <symbol id="{sid}" viewBox="0 0 24 24" fill="currentColor">{inner(fetch(SIMPLE.format(slug)))}</symbol>')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("<!-- Generated by tools/build_icons.py. Lucide 1.55.0 (ISC), Simple Icons 16.34.0 (CC0). -->\n"
                   '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + "\n</svg>\n", encoding="utf-8")
    print("wrote", OUT, len(symbols), "icons")


if __name__ == "__main__":
    main()
